#!/usr/bin/env node
/**
 * Command line of the geodata generator (ADR-0009).
 *
 *   npm run geo:build                    generate 3D assets for every pack
 *   npm run geo:build -- --pack <id>     ...for one pack (repeatable)
 *   npm run geo:verify                   check committed assets against their manifests and the budgets
 *   npm run unity -w @dunialab/geo       export 16-bit RAW heightmaps for Unity from the committed assets
 *
 * Options: --out <dir> (default content-assets), --cache <dir> (default .cache/geo),
 *          --no-landcover, --no-guides.
 * Data locations can be overridden for tests: GEO_DEM30_URL, GEO_DEM90_URL, GEO_WORLDCOVER_URL, GEO_RIVERS_FILE.
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { Assets3dManifest, DELIVERY_BUDGET, tilePath, validatePack, type AssetSource, type ContentPack } from "@dunialab/content";
import { toRaw16 } from "./bake.js";
import { generatePack } from "./generate.js";
import { readHeightWebp } from "./images.js";
import type { GeoParams } from "./plan.js";
import { copernicusDem, installRetryingFetch, naturalEarthRivers, newNetworkStats, worldCover } from "./remote.js";
import { lfsBytes, verifyAssets } from "./verify.js";

const ROOT = resolve(fileURLToPath(new URL("../../../", import.meta.url)));
const mb = (bytes: number) => `${(bytes / 1e6).toFixed(2)} MB`;

function parseArgs(argv: string[]) {
  const args = { command: argv[0] ?? "help", packs: [] as string[], out: "content-assets", cache: ".cache/geo", landcover: true, guides: true, to: "", params: {} as Partial<GeoParams> };
  for (let i = 1; i < argv.length; i++) {
    const a = argv[i]!;
    const value = () => {
      const v = argv[++i];
      if (v === undefined) throw new Error(`${a} needs a value`);
      return v;
    };
    if (a === "--pack") args.packs.push(value());
    else if (a === "--out") args.out = value();
    else if (a === "--cache") args.cache = value();
    else if (a === "--to") args.to = value();
    else if (a === "--no-landcover") args.landcover = false;
    else if (a === "--no-guides") args.guides = false;
    else if (a === "--params") args.params = JSON.parse(value()) as Partial<GeoParams>;
    else throw new Error(`unknown option ${a}`);
  }
  return args;
}

function loadPacks(only: string[]): ContentPack[] {
  const dir = process.env.GEO_PACKS_DIR ? resolve(process.env.GEO_PACKS_DIR) : join(ROOT, "packages", "content", "packs");
  const packs: ContentPack[] = [];
  for (const file of readdirSync(dir).filter((f) => f.endsWith(".json")).sort()) {
    const result = validatePack(JSON.parse(readFileSync(join(dir, file), "utf8")));
    if (!result.ok || !result.pack) throw new Error(`${file} is not a valid content pack:\n  ${result.issues.join("\n  ")}`);
    if (only.length === 0 || only.includes(result.pack.id)) packs.push(result.pack);
  }
  const unknown = only.filter((id) => !packs.some((p) => p.id === id));
  if (unknown.length) throw new Error(`no pack with id ${unknown.join(", ")} in ${dir}`);
  return packs;
}

const assetDirs = (out: string) =>
  existsSync(out)
    ? readdirSync(out, { withFileTypes: true })
        .filter((d) => d.isDirectory() && existsSync(join(out, d.name, "3d", "manifest.json")))
        .map((d) => join(out, d.name, "3d"))
    : [];

/** content-assets/ATTRIBUTION.md, generated from what the manifests say was used. */
function writeAttribution(out: string): void {
  const sources = new Map<string, AssetSource>();
  for (const dir of assetDirs(out)) {
    for (const s of Assets3dManifest.parse(JSON.parse(readFileSync(join(dir, "manifest.json"), "utf8"))).sources) sources.set(s.id, s);
  }
  const lines = [
    "# Data sources and required notices",
    "",
    "Generated by `npm run geo:build` from the asset manifests. Do not edit by hand.",
    "These notices must be shown wherever the 3D maps are shown (ADR-0009 section 4).",
    "Nothing here means that any of these organisations endorses DuniaLab.",
    "",
  ];
  for (const s of [...sources.values()].sort((a, b) => a.id.localeCompare(b.id, "en"))) {
    lines.push(`## ${s.title}`, "", `- Version: ${s.version}`, `- Licence: [${s.licence}](${s.licenceUrl})`, ...s.notices.map((n) => `- Notice: ${n}`), "");
  }
  writeFileSync(join(out, "ATTRIBUTION.md"), `${lines.join("\n")}`);
}

async function build(args: ReturnType<typeof parseArgs>): Promise<number> {
  const out = resolve(ROOT, args.out);
  const cacheDir = resolve(ROOT, args.cache);
  mkdirSync(cacheDir, { recursive: true });
  const log = (message: string) => console.log(message);
  const stats = newNetworkStats();
  const restore = installRetryingFetch(stats);
  const started = performance.now();
  let failed = 0;
  try {
    for (const pack of loadPacks(args.packs)) {
      console.log(`\n== ${pack.id} ==`);
      const dir = join(out, pack.id, "3d");
      await generatePack({
        pack,
        outDir: dir,
        params: args.params,
        log,
        sources: {
          elevation: copernicusDem({ cacheDir, log, baseUrl30: process.env.GEO_DEM30_URL, baseUrl90: process.env.GEO_DEM90_URL }),
          ...(args.landcover ? { landCover: worldCover({ cacheDir, log, baseUrl: process.env.GEO_WORLDCOVER_URL }) } : {}),
          ...(args.guides ? { guideRivers: naturalEarthRivers({ cacheDir, log, file: process.env.GEO_RIVERS_FILE }) } : {}),
        },
      });
      const problems = await verifyAssets(dir);
      for (const p of problems) console.error(`  PROBLEM ${p}`);
      failed += problems.length;
    }
  } finally {
    restore();
  }
  writeAttribution(out);
  const seconds = (performance.now() - started) / 1000;
  console.log(`\nnetwork: ${stats.requests} requests, ${mb(stats.bytes)} downloaded, ${stats.retries} retries; total time ${seconds.toFixed(0)} s`);
  report(out);
  return failed ? 1 : 0;
}

function report(out: string): void {
  let lfsTotal = 0;
  for (const dir of assetDirs(out)) {
    const m = Assets3dManifest.parse(JSON.parse(readFileSync(join(dir, "manifest.json"), "utf8")));
    lfsTotal += lfsBytes(dir);
    console.log(`${m.packId}: shipped ${mb(m.delivery.pack3dTotalBytes)} of ${mb(DELIVERY_BUDGET.pack3dTotalBytes)}; first 3D open ${mb(m.delivery.first3dOpenBytes)} of ${mb(DELIVERY_BUDGET.first3dOpenBytes)}`);
    for (const [id, bytes] of Object.entries(m.delivery.hdFeaturePatchBytes)) console.log(`  patch ${id}: ${mb(bytes)} of ${mb(DELIVERY_BUDGET.hdFeaturePatchBytes)}`);
  }
  console.log(`Git LFS total (images, previews included): ${mb(lfsTotal)} of the ${mb(DELIVERY_BUDGET.lfsStopAndAskBytes)} stop-and-ask limit`);
  if (lfsTotal > DELIVERY_BUDGET.lfsStopAndAskBytes) console.error("STOP: the Git LFS total is over the limit. Ask the founder before committing.");
}

async function verify(args: ReturnType<typeof parseArgs>): Promise<number> {
  const out = resolve(ROOT, args.out);
  const dirs = assetDirs(out);
  if (dirs.length === 0) {
    console.error(`no generated assets under ${out}`);
    return 1;
  }
  let failed = 0;
  for (const dir of dirs) {
    const problems = await verifyAssets(dir);
    console.log(`${dir}: ${problems.length === 0 ? "ok" : `${problems.length} problem(s)`}`);
    for (const p of problems) console.error(`  ${p}`);
    failed += problems.length;
  }
  report(out);
  return failed ? 1 : 0;
}

/** Unity Terrain imports 16-bit RAW heightmaps. They are derived from the committed tiles, so they are not committed. */
async function unity(args: ReturnType<typeof parseArgs>): Promise<number> {
  const out = resolve(ROOT, args.out);
  const to = resolve(ROOT, args.to || join(args.cache, "unity"));
  for (const dir of assetDirs(out)) {
    const m = Assets3dManifest.parse(JSON.parse(readFileSync(join(dir, "manifest.json"), "utf8")));
    const target = join(to, m.packId);
    mkdirSync(target, { recursive: true });
    const index: { file: string; size: number; minMetres: number; maxMetres: number; source: string }[] = [];
    const exportOne = async (source: string, name: string) => {
      const { data, width } = await readHeightWebp(join(dir, source));
      const raw = toRaw16(data);
      writeFileSync(join(target, `${name}.raw`), raw.bytes);
      index.push({ file: `${name}.raw`, size: width, minMetres: raw.minMetres, maxMetres: raw.maxMetres, source });
    };
    for (const set of [m.overview, m.regional]) for (const t of set.tiles) await exportOne(tilePath(set.zoom, t.x, t.y, "h"), `tile_${set.zoom}_${t.x}_${t.y}`);
    for (const p of m.patches) await exportOne(`${p.dir}/h.webp`, `patch_${p.featureId}`);
    writeFileSync(join(target, "index.json"), JSON.stringify({ packId: m.packId, byteOrder: "little-endian", bits: 16, heightmaps: index }, null, 1));
    console.log(`${m.packId}: ${index.length} RAW heightmaps in ${target}`);
  }
  return 0;
}

const args = parseArgs(process.argv.slice(2));
const commands: Record<string, (a: typeof args) => Promise<number>> = { build, verify, unity };
const command = commands[args.command];
if (!command) {
  console.log("usage: geo <build|verify|unity> [--pack <id>] [--out <dir>] [--cache <dir>] [--no-landcover] [--no-guides]");
  process.exit(args.command === "help" ? 0 : 1);
}
process.exit(await command(args));
